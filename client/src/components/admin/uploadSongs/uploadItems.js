import { metadataFromFilename, normalizeSongMetadata } from '../../../../../shared/songMetadata.mjs';

export const createUploadItem = (file, index) => ({
  id: `${Date.now()}-${index}-${file.name}`,
  file,
  sourceType: 'file',
  sourceUrl: null,
  name: file.name,
  progress: 0,
  stage: 'queued',
  stageLabel: null,
  status: 'pending',
  error: '',
  lyricsStatus: null,
  lyricsFormat: null,
  lyricsMessage: '',
  metadata: null,
  draftMetadata: metadataFromFilename(file.name),
  metadataEdits: {},
  metadataLoading: true,
  storageKey: null,
  postAction: null,
});

export const createYoutubeUploadItem = (url, index, hintTitle = '', metadata = null) => ({
  id: `${Date.now()}-${index}-yt`,
  file: null,
  sourceType: 'youtube',
  sourceUrl: url,
  hintTitle,
  name: url,
  progress: 0,
  stage: 'queued',
  stageLabel: null,
  status: 'pending',
  error: '',
  lyricsStatus: null,
  lyricsFormat: null,
  lyricsMessage: '',
  metadata: null,
  draftMetadata: metadata ? normalizeSongMetadata(metadata) : metadataFromFilename(hintTitle),
  metadataEdits: {},
  storageKey: null,
  postAction: null,
});
